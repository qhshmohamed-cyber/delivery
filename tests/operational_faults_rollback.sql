-- Backend fault acceptance using session/JWT contexts, not real-device sign-in.
-- Synthetic locations and suspension are uncommitted and always rolled back.
BEGIN;
CREATE TEMP TABLE operational_fault_results(test text,passed boolean);
DO $test$
DECLARE driver uuid; staff uuid; driver_sid uuid:=gen_random_uuid(); staff_sid uuid:=gen_random_uuid(); branch integer; company bigint; denied boolean; n integer; order_id bigint; tracking text:=translate(upper(substr(md5(gen_random_uuid()::text),1,8)),'01','XY'); response jsonb;
BEGIN
 SELECT p.user_id,p.branch_id,b.company_id INTO STRICT driver,branch,company FROM public.dlv_profiles p JOIN public.dlv_branches b ON b.id=p.branch_id JOIN public.dlv_companies c ON c.id=b.company_id WHERE p.active AND p.role='driver' AND b.active AND c.active AND c.onboarding_status='active' LIMIT 1;
 SELECT user_id INTO STRICT staff FROM public.dlv_profiles WHERE active AND workflow_role='callcenter_followup' AND branch_id=branch LIMIT 1;
 INSERT INTO auth.sessions(id,user_id,created_at,updated_at) VALUES(driver_sid,driver,now(),now()),(staff_sid,staff,now(),now());
 INSERT INTO public.dlv_orders(branch_id,order_no,created_by,track_code,customer_name,address,notes) VALUES(branch,'QA-FAULT-'||left(gen_random_uuid()::text,10),staff,tracking,'Synthetic customer','Synthetic address','Synthetic internal note') RETURNING id INTO order_id;
 EXECUTE 'SET LOCAL ROLE anon';response:=public.dlv_track(tracking)::jsonb;EXECUTE 'RESET ROLE';
 IF NOT coalesce((response->>'found')::boolean,false) THEN RAISE EXCEPTION 'Customer tracking unavailable';END IF;
 IF response ?| ARRAY['customer_name','phone','address','notes','created_by','driver_id'] OR response->>'pilot_phone' IS NOT NULL OR response->>'lat' IS NOT NULL OR response->>'lng' IS NOT NULL THEN RAISE EXCEPTION 'Tracking exposed private or premature location fields';END IF;
 UPDATE public.dlv_orders SET created_at=now()-interval '73 hours' WHERE id=order_id;
 EXECUTE 'SET LOCAL ROLE anon';response:=public.dlv_track(tracking)::jsonb;EXECUTE 'RESET ROLE';
 IF coalesce((response->>'found')::boolean,false) THEN RAISE EXCEPTION 'Expired tracking remained active';END IF;
 UPDATE public.dlv_orders SET created_at=now() WHERE id=order_id;
 INSERT INTO operational_fault_results VALUES('customer_tracking_minimal_fields_and_expiry',true);
 PERFORM set_config('request.jwt.claim.sub',driver::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',driver,'session_id',driver_sid,'exp',extract(epoch from now()+interval '1 hour')::bigint,'aal','aal1')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 PERFORM public.dlv_update_location(30,31,10);
 IF NOT EXISTS(SELECT 1 FROM public.dlv_locations WHERE driver_id=auth.uid()) THEN RAISE EXCEPTION 'Own location not recorded';END IF;
 denied:=false;BEGIN PERFORM public.dlv_update_location(91,31,10);EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Invalid latitude accepted';END IF;
 denied:=false;BEGIN PERFORM public.dlv_update_location(30,181,10);EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Invalid longitude accepted';END IF;
 denied:=false;BEGIN PERFORM public.dlv_update_location(30,31,-1);EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Invalid accuracy accepted';END IF;
 EXECUTE 'RESET ROLE';
 INSERT INTO operational_fault_results VALUES('driver_location_write_and_invalid_coordinates',true);
 UPDATE public.dlv_companies SET active=false WHERE id=company;
 EXECUTE 'SET LOCAL ROLE anon';response:=public.dlv_track(tracking)::jsonb;EXECUTE 'RESET ROLE';
 IF coalesce((response->>'found')::boolean,false) THEN RAISE EXCEPTION 'Suspended company tracking remained active';END IF;
 EXECUTE 'SET LOCAL ROLE authenticated';
 IF public.dlv_role() IS NOT NULL OR public.dlv_can_access_branch(branch) THEN RAISE EXCEPTION 'Suspended company access remained';END IF;
 SELECT count(*) INTO n FROM public.dlv_orders;IF n<>0 THEN RAISE EXCEPTION 'Suspended company orders visible';END IF;
 denied:=false;BEGIN PERFORM public.dlv_update_location(30,31,10);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Suspended driver location write remained';END IF;
 EXECUTE 'RESET ROLE';
 UPDATE public.dlv_companies SET active=true WHERE id=company;
 IF NOT EXISTS(SELECT 1 FROM public.dlv_orders WHERE id=order_id) THEN RAISE EXCEPTION 'Suspension deleted order data';END IF;
 EXECUTE 'SET LOCAL ROLE authenticated';
 IF public.dlv_role()<>'driver' OR NOT public.dlv_can_access_branch(branch) THEN RAISE EXCEPTION 'Reactivated company access not restored';END IF;
 EXECUTE 'RESET ROLE';
 INSERT INTO operational_fault_results VALUES('company_suspend_resume_same_session_and_no_data_delete',true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',driver,'session_id',driver_sid,'exp',extract(epoch from now()-interval '1 minute')::bigint,'aal','aal1')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 IF public.dlv_session_valid() THEN RAISE EXCEPTION 'Expired access token accepted';END IF;
 SELECT count(*) INTO n FROM public.dlv_orders;IF n<>0 THEN RAISE EXCEPTION 'Expired session reads orders';END IF;
 EXECUTE 'RESET ROLE';
 INSERT INTO operational_fault_results VALUES('expired_jwt_denies_data',true);
 PERFORM set_config('request.jwt.claim.sub',staff::text,true);
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',staff,'session_id',staff_sid,'exp',extract(epoch from now()+interval '1 hour')::bigint,'aal','aal1')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 denied:=false;BEGIN PERFORM public.dlv_update_location(30,31,10);EXCEPTION WHEN OTHERS THEN denied:=true;END;
 IF NOT denied THEN RAISE EXCEPTION 'Non-driver sent driver location';END IF;
 EXECUTE 'RESET ROLE';
 INSERT INTO operational_fault_results VALUES('non_driver_location_write_denied',true);
END $test$;
SELECT * FROM operational_fault_results;
ROLLBACK;
