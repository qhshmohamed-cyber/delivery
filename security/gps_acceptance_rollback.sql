-- Synthetic location/order/session fixtures are rolled back by the exception block.
DO $$
DECLARE d uuid;s uuid;sid uuid:=gen_random_uuid();bid integer;other_bid integer;j jsonb;oid bigint;code text:='QAGPS234';passed integer:=0;t timestamptz;
BEGIN
 BEGIN
  SELECT user_id,branch_id INTO d,bid FROM public.dlv_profiles WHERE active AND role='driver' AND workflow_role='driver' AND branch_id=ANY(allowed_branch_ids) ORDER BY branch_id LIMIT 1;
  SELECT user_id INTO s FROM public.dlv_profiles WHERE active AND workflow_role='supervisor' AND branch_id=bid LIMIT 1;
  SELECT id INTO other_bid FROM public.dlv_branches WHERE id<>bid ORDER BY id LIMIT 1;
  IF d IS NULL OR s IS NULL OR other_bid IS NULL THEN RAISE EXCEPTION 'Missing GPS QA roles';END IF;
  INSERT INTO auth.sessions(id,user_id,created_at,updated_at) VALUES(sid,d,now(),now());
  PERFORM set_config('request.jwt.claim.sub',d::text,true);
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',d,'session_id',sid,'exp',extract(epoch from now()+interval '1 hour')::bigint)::text,true);
  DELETE FROM public.dlv_locations WHERE driver_id=d;
  t:=clock_timestamp()-interval '10 seconds';
  j:=public.dlv_update_location_v2(30.05,31.2,8,t);
  IF j->>'accepted'<>'true' THEN RAISE EXCEPTION 'Fresh sample rejected: %',j;END IF;passed:=passed+1;
  j:=public.dlv_update_location_v2(30.05,31.2,8,t-interval '1 second');
  IF j->>'reason'<>'older_sample' THEN RAISE EXCEPTION 'Older sample accepted';END IF;passed:=passed+1;
  j:=public.dlv_update_location_v2(30.05,31.2,8,clock_timestamp()-interval '21 seconds');
  IF j->>'reason'<>'sample_time' THEN RAISE EXCEPTION 'Old fix accepted';END IF;passed:=passed+1;
  j:=public.dlv_update_location_v2(30.05,31.2,8,clock_timestamp()+interval '10 seconds');
  IF j->>'reason'<>'sample_time' THEN RAISE EXCEPTION 'Future fix accepted';END IF;passed:=passed+1;
  BEGIN PERFORM public.dlv_update_location_v2(30,31,151,clock_timestamp());RAISE EXCEPTION 'Bad accuracy accepted';EXCEPTION WHEN invalid_parameter_value THEN passed:=passed+1;END;
  BEGIN PERFORM public.dlv_update_location_v2('NaN'::float8,31,8,clock_timestamp());RAISE EXCEPTION 'NaN accepted';EXCEPTION WHEN invalid_parameter_value THEN passed:=passed+1;END;
  BEGIN PERFORM public.dlv_update_location_v2(30,'Infinity'::float8,8,clock_timestamp());RAISE EXCEPTION 'Infinity accepted';EXCEPTION WHEN invalid_parameter_value THEN passed:=passed+1;END;
  BEGIN PERFORM public.dlv_update_location_v2(30,31,NULL,clock_timestamp());RAISE EXCEPTION 'Unknown accuracy accepted';EXCEPTION WHEN invalid_parameter_value THEN passed:=passed+1;END;
  UPDATE public.dlv_locations SET updated_at=clock_timestamp()-interval '3 seconds' WHERE driver_id=d;
  j:=public.dlv_update_location_v2(31.05,31.2,8,t+interval '5 seconds');
  IF j->>'reason'<>'implausible_jump' OR NOT EXISTS(SELECT 1 FROM public.dlv_locations WHERE driver_id=d AND lat=30.05) THEN RAISE EXCEPTION 'Teleport changed stored fix';END IF;passed:=passed+1;
  j:=public.dlv_update_location_v2(30.05005,31.20005,8,t+interval '5 seconds');
  IF j->>'accepted'<>'true' THEN RAISE EXCEPTION 'Realistic move rejected: %',j;END IF;passed:=passed+1;
  BEGIN PERFORM * FROM public.dlv_map_locations(bid);RAISE EXCEPTION 'Driver read manager map';EXCEPTION WHEN insufficient_privilege THEN passed:=passed+1;END;
  SELECT coalesce(min(id),0)-1 INTO oid FROM public.dlv_orders;
  WHILE EXISTS(SELECT 1 FROM public.dlv_orders WHERE track_code=code) LOOP code:=translate(upper(substr(md5(gen_random_uuid()::text),1,8)),'01IO','23JK');END LOOP;
  INSERT INTO public.dlv_orders(id,branch_id,order_no,created_by,driver_id,status,workflow_stage,track_code) OVERRIDING SYSTEM VALUE VALUES(oid,bid,'QA GPS rollback',s,d,'out','out',code);
  j:=public.dlv_track(code)::jsonb;
  IF j->>'lat' IS NULL OR j->>'accuracy'<>'8' OR j->>'server_at' IS NULL THEN RAISE EXCEPTION 'Fresh public tracking failed: %',j;END IF;passed:=passed+1;
  UPDATE public.dlv_locations SET recorded_at=clock_timestamp()-interval '61 seconds' WHERE driver_id=d;
  j:=public.dlv_track(code)::jsonb;IF j->>'lat' IS NOT NULL THEN RAISE EXCEPTION 'Stale public fix leaked';END IF;passed:=passed+1;
  UPDATE public.dlv_locations SET recorded_at=clock_timestamp()+interval '1 minute' WHERE driver_id=d;
  j:=public.dlv_track(code)::jsonb;IF j->>'lat' IS NOT NULL THEN RAISE EXCEPTION 'Future public fix leaked';END IF;passed:=passed+1;
  UPDATE public.dlv_locations SET recorded_at=clock_timestamp(),branch_id=other_bid WHERE driver_id=d;
  j:=public.dlv_track(code)::jsonb;IF j->>'lat' IS NOT NULL THEN RAISE EXCEPTION 'Other branch public fix leaked';END IF;passed:=passed+1;
  UPDATE public.dlv_locations SET branch_id=bid WHERE driver_id=d;
  UPDATE public.dlv_profiles SET active=false WHERE user_id=d;
  j:=public.dlv_track(code)::jsonb;IF j->>'lat' IS NOT NULL THEN RAISE EXCEPTION 'Inactive driver public fix leaked';END IF;passed:=passed+1;
  UPDATE public.dlv_profiles SET active=true WHERE user_id=d;
  UPDATE public.dlv_orders SET status='delivered',delivered_at=now() WHERE id=oid;
  j:=public.dlv_track(code)::jsonb;IF j->>'lat' IS NOT NULL THEN RAISE EXCEPTION 'Completed order public fix leaked';END IF;passed:=passed+1;
  DELETE FROM auth.sessions WHERE id=sid;
  INSERT INTO auth.sessions(id,user_id,created_at,updated_at) VALUES(sid,s,now(),now());
  PERFORM set_config('request.jwt.claim.sub',s::text,true);
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',s,'session_id',sid,'exp',extract(epoch from now()+interval '1 hour')::bigint)::text,true);
  PERFORM * FROM public.dlv_map_locations(bid);passed:=passed+1;
  BEGIN PERFORM * FROM public.dlv_map_locations(other_bid);RAISE EXCEPTION 'Other branch map accessible';EXCEPTION WHEN insufficient_privilege THEN passed:=passed+1;END;
  BEGIN PERFORM public.dlv_update_location_v2(30,31,8,clock_timestamp());RAISE EXCEPTION 'Supervisor wrote driver GPS';EXCEPTION WHEN insufficient_privilege THEN passed:=passed+1;END;
  RAISE SQLSTATE 'ZQGPS';
 EXCEPTION WHEN SQLSTATE 'ZQGPS' THEN NULL;
 END;
 IF EXISTS(SELECT 1 FROM auth.sessions WHERE id=sid) OR EXISTS(SELECT 1 FROM public.dlv_orders WHERE id=oid) THEN RAISE EXCEPTION 'GPS fixtures retained';END IF;
 RAISE NOTICE 'GPS QA: % checks passed; all fixtures rolled back',passed;
 PERFORM set_config('yourstaff.gps_qa',jsonb_build_object('passed',passed,'fixtures_rolled_back',true)::text,true);
END $$;
SELECT current_setting('yourstaff.gps_qa')::jsonb AS gps_acceptance;
